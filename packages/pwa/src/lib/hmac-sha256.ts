/**
 * A small synchronous HMAC-SHA-256, used for one thing: the UPI `tr` transaction reference
 * (DECISIONS/0024 S3 pin 4). `crypto.subtle` is asynchronous, and the reference is not a secret — it is a
 * deterministic label derived from a token that is already in the locked document — so a dependency-free
 * implementation keeps the settlement view a pure synchronous projection.
 *
 * This is not used for encryption, signatures or password hashing. Ticket 16's codec uses WebCrypto.
 */

